// One-time dependency for maintainers; the site itself needs neither npm nor a CDN.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const version = require('highlight.js/package.json').version;
if (version !== '11.11.2') throw new Error('Use highlight.js@11.11.2 to rebuild the vendored asset');

await build({
  absWorkingDir: root,
  entryPoints: ['tools/code-highlight.mjs'],
  outfile: 'assets/js/code-highlight.js',
  bundle: true,
  format: 'iife',
  target: ['es2018'],
  minify: true,
  legalComments: 'none',
  banner: {js: '/* Highlight.js 11.11.2 (BSD-3-Clause) + site grammars. See highlight.LICENSE.txt. Generated by tools/build-code-highlight.mjs. */'}
});

const packageDir = path.dirname(require.resolve('highlight.js/package.json'));
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(root, 'assets/js/highlight.LICENSE.txt'));

"""Independent exact arithmetic for every major Ch37 teaching quantity."""
from fractions import Fraction as F
from pathlib import Path
import json
checks=[]
def verify(label,value,expected):
    assert value==expected,(label,value,expected)
    checks.append({'label':label,'value':str(value),'expected':str(expected)})
day=40*86400;year=day*365;payload=year*1500;index=year*(2*40);total=payload+index
verify('peak checkout/s',40*8,320)
verify('mean read QPS',40*20,800)
verify('peak read QPS',320*20,6400)
verify('orders/day',day,3456000)
verify('orders/365-day year',year,1261440000)
verify('snapshot B/year',payload,1892160000000)
verify('snapshot TB/year',F(payload,10**12),F('1.89216'))
verify('two indexes B/order',2*40,80)
verify('index B/year',index,100915200000)
verify('index TB/year',F(index,10**12),F('0.1009152'))
verify('one copy total B/year',total,1993075200000)
verify('one copy total TB/year',F(total,10**12),F('1.9930752'))
verify('three live plus one compact backup TB',F(4*total,10**12),F('7.9723008'))
verify('live versions plus compact backup multiplier',3*F('1.5')+1,F('5.5'))
verify('versions storage TB',total*F('5.5')/10**12,F('10.9619136'))
verify('peak fresh snapshots B/s',320*1500,480000)
verify('peak fresh snapshots decimal MB/s',F(320*1500,10**6),F('.48'))
verify('8 KiB page B',8*1024,8192)
verify('three page B/order',3*8192,24576)
verify('three page model B/s',320*3*8192,7864320)
verify('three page model MB/s',F(320*3*8192,10**6),F('7.86432'))
verify('model page/payload amplification',F(3*8192,1500),F('16.384'))
verify('hot SKU requests/s',320*F('.30'),96)
verify('hot serial mean occupancy',96*F('.010'),F('.96'))
verify('chat bytes/s',2000*400,800000)
verify('chat MB/s',F(2000*400,10**6),F('.8'))
verify('50 messages B',50*400,20000)
verify('posting bytes/document',80*20,1600)
verify('amount stripe all-fragment GB',F(year*8,10**9),F('10.09152'))
verify('amount plus status GB',F(year*9,10**9),F('11.35296'))
verify('raw row/amount byte ratio',F(1500,8),F('187.5'))
verify('WA6 disk write MB/s',10*6,60)
verify('WA12 disk write MB/s',10*12,120)
verify('WA12 exceeds budget MB/s',120-100,20)
verify('healthy quorum overlap',sorted({'N1','N2'}&{'N2','N3'}),['N2'])
verify('sloppy disjoint quorum',sorted({'N1','N4'}&{'N2','N3'}),[])
verify('naive inequality still true with wrong membership',2+2>3,True)
Path(__file__).with_name('ch37-independent-numeric-results.json').write_text(json.dumps({'passed':True,'checks':checks},ensure_ascii=False,indent=2)+'\n')
print(f'PASS {len(checks)} independent arithmetic/set checks; not a benchmark')

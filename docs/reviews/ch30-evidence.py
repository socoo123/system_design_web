from pathlib import Path
import hashlib,html,json,re
R=Path(__file__).resolve().parents[2]
page=R/'chapters/ch30.html';s=page.read_text();old=(R/'docs/reviews/ch28-ch29-ch30-baseline/ch30.html').read_text()
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
checks=[]
def check(name,ok):
 if not ok:raise AssertionError(name)
 checks.append(name)
svgs=lambda text:re.findall(r'<svg\b[\s\S]*?</svg>',text)
ids=lambda text:re.findall(r'<(?:title|desc) id="([^"]+)"',text)
oldsvg,newsvg=svgs(old),svgs(s)
check('all32 frames and original accessible IDs/order',len(newsvg)==32 and ids(old)==ids(s))
changed=[re.search(r'<title id="([^"]+)"',b)[1] for a,b in zip(oldsvg,newsvg) if a!=b]
check('only9 SVG text-only corrections',changed==['d2s6t','d3s3t','d3s4t','d3s5t','d5s1t','d5s2t','d5s3t','d5s4t','d5s5t'])
striptext=lambda x:re.sub(r'(<text\b[^>]*>)[\s\S]*?(</text>)',r'\1\2',x)
check('all32 SVG geometries and routes unchanged',all(striptext(a)==striptext(b) for a,b in zip(oldsvg,newsvg)))
blocks=re.findall(r'<pre\b([^>]*)><code>([\s\S]*?)</code></pre>',s)
check('six shared-source labelled blocks',len(blocks)==6 and all('data-kind=' in a and 'data-language=' in a and 'data-source=' in a for a,b in blocks))
check('English-only code comments',not any(re.search('[\u3400-\u9fff]',html.unescape(b)) for _,b in blocks))
check('bilingual node inventories correspond',s.count('class="lang-zh"')==s.count('class="lang-en"'))
check('fourteen flashcards in shared grid',s.count('class="flip"')==14 and '<div class="cards-grid">' in s)
check('no generated bytecode in examples',not list((R/'examples/ch30').rglob('*.pyc')) and not list((R/'examples/ch30').rglob('*.class')))
code=json.loads((R/'docs/reviews/ch30-code-results.json').read_text())
check('executedSQLite51 numeric21 Java20',code['passed'] and code['sqlite_assertions']==51 and code['numeric_assertions']==21 and '20 assertions' in code['java_stdout'])
for f,h in code['sha256'].items():check('code hash:'+f,sha(R/f)==h)
b=json.loads((R/'docs/reviews/ch30-browser-results.json').read_text())
check('24 layouts bound to finalHTML',b['files']['ch30']==sha(page) and len(b['layouts'])==24 and b['passed'])
check('actual viewport no page overflow before/after details',all(x['width']==x['scrollWidth']==x['expanded']['scrollWidth'] for x in b['layouts']))
check('128 frame visits six exact copies and interactions',sum(x['frameVisits'] for x in b['layouts'])==128 and b['interactions'][0]['copied']==6 and not b['errors'] and all(b['interactions'][0][k] for k in ('keyboard','playback','flashcards','progress','settings')))
r=json.loads((R/'docs/reviews/ch30-after-render-results.json').read_text())
check('64 two-theme frames bound to finalHTML',r['sha256']==sha(page) and len(r['frames'])==64)
g=json.loads((R/'docs/reviews/ch30-geometry-after.json').read_text())['chapters']['ch30']
check('geometry bound to finalHTML',g['sha256']==sha(page))
check('geometry no invalid/clipped/boundary/node crossings',all(not f[k] for f in g['frames'] for k in ('invalidNumbers','clipped','boundaryCrossings','nodeCrossings')))
# Actual visual review was performed with view_image, not inferred from this list.
viewed=[R/f'docs/reviews/screenshots/ch30-before/contact-d{d}-{t}.png' for t in ('parchment','dracula') for d in range(1,7)]
viewed += [R/f'docs/reviews/screenshots/ch30-browser/contact-{kind}-d{d}-{t}.png' for t in ('parchment','dracula') for d in (2,3,5) for kind in ('page','phone')]
viewed += [R/'docs/reviews/screenshots/ch30-browser'/p for p in ('320-parchment-en-top.png','1440-dracula-en-top.png','ch30-1440-parchment-code.png','ch30-390-parchment-code.png')]
check('28 actually viewed representative/contact images exist',len(viewed)==28 and all(p.exists() for p in viewed))
plain=lambda text:re.sub(r'<[^>]+>','',re.sub(r'<(?:svg|pre)\b[\s\S]*?</(?:svg|pre)>','',text))
stats=dict(decks=6,frames=32,changedSVG=changed,unchangedSVG=23,geometryChanged=0,codeBlocks=6,codeLines=sum(len(html.unescape(b).splitlines()) for _,b in blocks),flashcards=14,
 beforeChineseChars=len(re.findall('[\u3400-\u9fff]',plain(old))),afterChineseChars=len(re.findall('[\u3400-\u9fff]',plain(s))))
out=dict(passed=len(checks),failed=0,htmlSHA256=sha(page),checks=checks,stats=stats,viewedImageHashes={str(p.relative_to(R)):sha(p) for p in viewed},geometryNote='Store title/subtitle line boxes overlap slightly; actual glyphs are separate. Geometry/screenshot generation does not establish visual review.')
(R/'docs/reviews/ch30-evidence-results.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(dict(passed=len(checks),failed=0,stats=stats),ensure_ascii=False))
